function out = build_gemm_out(C_hat, C_ref, metrics, Q_A, Q_B, Acc, K, p_A, p_B, ...
                              quantA_label, quantB_label)
    out = struct();
    out.C = C_hat;
    out.C_ref = C_ref;
    out.relative_error = metrics.fro_relative_error;
    out.absolute_error = metrics.fro_absolute_error;
    out.error_metrics = metrics;
    out.A_quant = Q_A;
    out.B_quant = Q_B;
    out.accumulator = Acc;
    out.integer_emulation = struct( ...
        'quantization', 'symmetric', ...
        'zero_point', 0, ...
        'matmul', 'integer @ integer', ...
        'accumulation', 'full dot product before dequantization', ...
        'quant_dtype_A', string(class(Q_A)), ...
        'quant_dtype_B', string(class(Q_B)), ...
        'accumulator_dtype', string(class(Acc)), ...
        'K', K);

    out.params = struct();
    out.params.A = struct( ...
        'quantization', quantA_label.quantization, ...
        'channel_axis', quantA_label.channel_axis, ...
        'channel_meaning', quantA_label.channel_meaning, ...
        'scale', p_A.scale, ...
        'zero_point', p_A.zero_point, ...
        'axis', p_A.axis, ...
        'qmin', p_A.qmin, ...
        'qmax', p_A.qmax, ...
        'dtype', string(p_A.dtype));
    out.params.B = struct( ...
        'quantization', quantB_label.quantization, ...
        'channel_axis', quantB_label.channel_axis, ...
        'channel_meaning', quantB_label.channel_meaning, ...
        'scale', p_B.scale, ...
        'zero_point', p_B.zero_point, ...
        'axis', p_B.axis, ...
        'qmin', p_B.qmin, ...
        'qmax', p_B.qmax, ...
        'dtype', string(p_B.dtype));
end